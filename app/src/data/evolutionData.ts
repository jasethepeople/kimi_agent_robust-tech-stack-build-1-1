export function getPhaseById(id: number): Phase | undefined {
  return phases.find((p) => p.id === id);
}

export function getSuperPhaseById(id: number): SuperPhase | undefined {
  return superPhases.find((s) => s.id === id);
}

export function getPhasesBySuperPhase(superPhaseId: number): Phase[] {
  return phases.filter((p) => p.superPhaseId === superPhaseId);
}

export function getPhaseColor(phaseId: number): string {
  const phase = getPhaseById(phaseId);
  if (!phase) return '#06B6D4';
  const superPhase = getSuperPhaseById(phase.superPhaseId);
  return superPhase?.color ?? '#06B6D4';
}
